import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const README = join(ROOT, 'README.md');
const TOKEN = process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
const PERIOD_DAYS = 30;

const QUERIES = [
  'topic:claude-skills',
  'topic:agent-skills',
  'topic:ai-skills',
  'claude skills in:name,description',
  'agent skills in:name sort:stars'
];

async function search(query, page = 1) {
  const params = new URLSearchParams({ q: query, sort: 'stars', order: 'desc', per_page: '100', page: String(page) });
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'claude-skills-leaderboard' };
  if (TOKEN) headers.Authorization = `Bearer ${TOKEN}`;
  const res = await fetch(`https://api.github.com/search/repositories?${params}`, { headers });
  if (res.status === 403 || res.status === 429) {
    console.warn(`Rate limited on query "${query}", skipping.`);
    return { items: [], total: 0 };
  }
  if (!res.ok) {
    console.warn(`Query "${query}" failed with ${res.status}, skipping.`);
    return { items: [], total: 0 };
  }
  return res.json();
}

function looksLikeSkillRepo(repo) {
  const text = `${repo.name} ${repo.description || ''} ${repo.topics?.join(' ') || ''}`.toLowerCase();
  return /(skill|skills)/.test(text) && /(claude|agent|codex|cursor|gemini|llm|ai)/.test(text);
}

function truncate(text, max = 140) {
  if (!text) return '';
  const clean = text.replace(/\s+/g, ' ').trim();
  return clean.length > max ? `${clean.slice(0, max - 1)}...` : clean;
}

function table(rows, offset = 0) {
  const lines = ['| # | Repository | Stars | Forks | Description |', '| ---: | --- | ---: | ---: | --- |'];
  rows.forEach((repo, index) => {
    const name = `[${repo.full_name}](https://github.com/${repo.full_name})`;
    lines.push(`| ${index + 1 + offset} | ${name} | ${repo.stargazers_count.toLocaleString('en-US')} | ${repo.forks_count.toLocaleString('en-US')} | ${truncate(repo.description)} |`);
  });
  return lines.join('\n');
}

async function main() {
  const merged = new Map();
  for (const query of QUERIES) {
    const { items } = await search(query);
    for (const repo of items) {
      if (!looksLikeSkillRepo(repo)) continue;
      if (!merged.has(repo.id)) merged.set(repo.id, repo);
    }
  }

  const cutoff = Date.now() - PERIOD_DAYS * 24 * 60 * 60 * 1000;
  const all = [...merged.values()].sort((a, b) => b.stargazers_count - a.stargazers_count);
  const trending = all
    .filter((repo) => new Date(repo.created_at).getTime() >= cutoff)
    .sort((a, b) => b.stargazers_count - a.stargazers_count);

  const top = all.slice(0, 25);
  const fresh = trending.slice(0, 15);

  const readme = readFileSync(README, 'utf8');
  const start = '<!-- LEADERBOARD:START -->';
  const end = '<!-- LEADERBOARD:END -->';
  const startIndex = readme.indexOf(start);
  const endIndex = readme.indexOf(end);
  if (startIndex === -1 || endIndex === -1) {
    console.error('README is missing LEADERBOARD:START/END markers.');
    process.exit(1);
  }

  const updated = new Date().toISOString().replace('T', ' ').slice(0, 19);
  const sections = [
    start,
    '',
    `Last updated: ${updated} UTC (auto-generated by GitHub Actions, every hour).`,
    '',
    '## Top 25 most starred Claude skill repositories',
    '',
    table(top),
    '',
    `## Trending: new skill repos from the last ${PERIOD_DAYS} days`,
    '',
    fresh.length > 0 ? table(fresh) : `No new skill repositories matched in the last ${PERIOD_DAYS} days.`,
    '',
    end
  ];

  const next = readme.slice(0, startIndex) + sections.join('\n') + readme.slice(endIndex + end.length);
  writeFileSync(README, next);

  const slim = (repo) => ({
    repository: repo.full_name,
    url: repo.html_url,
    stars: repo.stargazers_count,
    forks: repo.forks_count,
    description: repo.description || '',
    created_at: repo.created_at
  });
  const json = {
    generated_at: new Date().toISOString(),
    source: 'github-search-api',
    queries: QUERIES,
    total_tracked: all.length,
    top: top.map(slim),
    trending_last_days: { period_days: PERIOD_DAYS, repositories: fresh.map(slim) }
  };
  writeFileSync(join(ROOT, 'leaderboard.json'), `${JSON.stringify(json, null, 2)}\n`);

  const llms = [
    '# Claude Skills Leaderboard',
    '',
    'Live ranking of the most starred AI agent skill repositories on GitHub, updated hourly by GitHub Actions from the GitHub Search API.',
    '',
    `Generated: ${updated} UTC. Total repositories tracked: ${all.length}.`,
    '',
    '## Top 10 most starred skill repositories',
    '',
    ...top.slice(0, 10).map((repo, i) => `${i + 1}. ${repo.full_name}: ${repo.stargazers_count} stars. ${truncate(repo.description, 200)} (${repo.html_url})`),
    '',
    `## Trending new skill repositories (last ${PERIOD_DAYS} days)`,
    '',
    ...(fresh.length > 0
      ? fresh.slice(0, 10).map((repo, i) => `${i + 1}. ${repo.full_name}: ${repo.stargazers_count} stars. ${truncate(repo.description, 200)} (${repo.html_url})`)
      : ['None matched in this period.']),
    '',
    '## Full data',
    '',
    '- Markdown leaderboard: https://github.com/clements23/claude-skills-leaderboard#live-leaderboard',
    '- Machine-readable JSON: https://github.com/clements23/claude-skills-leaderboard/blob/main/leaderboard.json',
    '- Raw JSON: https://raw.githubusercontent.com/clements23/claude-skills-leaderboard/main/leaderboard.json',
    '',
    'To get listed, add the claude-skills or agent-skills topic to your repository and mention skills in the name or description.',
    ''
  ].join('\n');
  writeFileSync(join(ROOT, 'llms.txt'), llms);

  console.log(`Leaderboard updated: ${all.length} repositories tracked, ${top.length} ranked, ${fresh.length} trending. JSON and llms.txt written.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
